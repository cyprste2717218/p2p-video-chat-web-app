function sendMsg(message) {
	if (websocket) {
		console.log("message to send from to ws server (not stringified):",message);
		console.log("message to send from to ws server (stringified):",JSON.stringify(message));
		return websocket.send(JSON.stringify(message));
	}

	console.error("No active websocket connection to send message through");
	return;

}

export async function connectToCall(data) {
	try {

		const {callURL,callID,emailInput,usernameInput}=data;

		// fetch and display local video 
		await getLocalMedia();

		// establish connection to websocket server created
		await establishWebSocketServerConn(callURL);

		// set up ws event handlers to respond to messages receieved
		await attachWSConnListeners(emailInput.value);

		// start connection negotiation process with any current call participants
		sendJoiningMessage(usernameInput.value,emailInput.value,callID);

	} catch (err) {
		console.error(`Error configuring connection to call ${callID}`)
	}
}

// Create RTCPeerConnection object for client device
function createPeerConnection(caller,recipient,peerUser,callID) {

	function handleICECandidateEvent(event) {
		console.log("ICE candidate generated by browser:");

		if (!event.candidate) {
			console.log(`Finished gathering ICE candidates for connection to ${recipient}`);
			return;
		}

		if (event.candidate.candidate==="") {
			console.log(`No more ICE candidates to send to ${recipient}`);
			return;
		}

		const msg={
			type: "candidate",
			data: {"candidate": event.candidate,"recipient": recipient,"caller": caller,callID: callID}
		}

		return sendMsg(msg);
	}

	function handleTrackEvent(event) {

		function addNewVideoElement() {
			// update DOM with video for newly joined participant
			const cameraBoxContainer=document.getElementById('camera-box');
			const newVideoContainer=document.createElement('div');

			const newParticipantName=document.createElement('p');
			newParticipantName.textContent=peerUser;

			const newVideoElem=document.createElement('video');
			newVideoElem.id=`video-from-${peerUser}`;
			newVideoElem.autoplay=true;
			newVideoElem.muted=false;

			newVideoContainer.appendChild(newVideoElem);
			newVideoContainer.appendChild(newParticipantName);
			cameraBoxContainer.appendChild(newVideoContainer);

			newVideoElem.srcObject=event.streams[0];


		}

		console.log("track event triggered:");

		try {

			const activeVideoElement=document.getElementById(`video-from-${peerUser}`);
			if (activeVideoElement) {
				console.log("Video stream already present for participant:",peerUser);
				return;

			} else {
				addNewVideoElement();
			}

		} catch (err) {
			console.error("An error occured attaching new video stream to DOM");
		}



	}

	function handleNegotiationNeededEvent() {
		console.log("Negotiation needed event triggered");
	}

	function handleRemoveTrackEvent() {
		console.log("remove track event triggered")
	}

	function handleICEConnectionStateChangeEvent() {
		console.log("ICE connection state change event triggered")
	}

	function handleICEGatheringStateChangeEvent() {
		console.log("ICE gathering state change event triggered")
	}

	function handleSignalingStateChangeEvent(ev) {
		console.log("signalling state change event triggered:",ev);
	}

	const myPeerConnection=new RTCPeerConnection({
		iceServers: [
			{
				urls: "stun:stun.stunprotocol.org",
			},
		],
	});

	myPeerConnection.caller=caller;
	myPeerConnection.recipient=recipient;
	myPeerConnection.peerUser=peerUser;
	myPeerConnection.onicecandidate=handleICECandidateEvent;
	myPeerConnection.ontrack=handleTrackEvent;
	myPeerConnection.onnegotiationneeded=handleNegotiationNeededEvent;
	myPeerConnection.onremovetrack=handleRemoveTrackEvent;
	myPeerConnection.oniceconnectionstatechange=
		handleICEConnectionStateChangeEvent;
	myPeerConnection.onicegatheringstatechange=
		handleICEGatheringStateChangeEvent;
	myPeerConnection.onsignalingstatechange=handleSignalingStateChangeEvent;

	return myPeerConnection;
}

// Returns existing peer connection or create new one if doesn't exist
function isExistingPeerConnection(type,caller,recipient,callID) {

	try {
		let existingPeerConnection;

		let peerConnectionIndex=peerConnectionsArr.findIndex(peerConection => peerConection.recipient===recipient&&peerConection.caller===caller);

		if (peerConnectionIndex!==-1) {
			existingPeerConnection=peerConnectionsArr[peerConnectionIndex];
		} else {

			if (!(type==="sendingOffer"||type==="receivingOffer")) {
				throw new Error("RTC connection obj should already exist");
			}

			let peerUser;

			if (type==="sendingOffer") {
				peerUser=recipient;
			} else if (type==="receivingOffer") {
				peerUser=caller;
			} else {
				throw new Error("Neither recognised valid types for situations warranting creating RTCPeerConnection obj");
			}

			const newPeerConnection=createPeerConnection(caller,recipient,peerUser,callID);
			existingPeerConnection=newPeerConnection;

			peerConnectionsArr.push(existingPeerConnection);
			peerConnectionIndex=peerConnectionsArr.length-1;
		}

		const currentPeerConnection=existingPeerConnection;

		return {currentPeerConnection: currentPeerConnection,peerConnectionIndex: peerConnectionIndex};

	} catch (err) {
		console.error("An error occured checking for existing peer connection:",err);
	}

}

